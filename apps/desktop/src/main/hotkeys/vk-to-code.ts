const EXTENDED_KEY_MASK = 0x01

export interface ObservedKey {
  code: string
  keyCode: number
  isExtended: boolean
  isInjected: boolean
  isUp: boolean
}

export function vkToCode(vkCode: number): string {
  // An unmapped VK must not masquerade as a DOM key code, or a bound key silently stops working.
  return VK_TO_CODE.get(vkCode) ?? `Unmapped-${vkCode.toString(16).toUpperCase().padStart(2, '0')}`
}

export function decodeKeyRecord(vkCode: number, scanCode: number, flags: number): ObservedKey {
  const code = vkToCode(vkCode)
  const rightHanded = /Left$/.test(code) && (flags & EXTENDED_KEY_MASK) !== 0
  return {
    code: rightHanded ? code.replace(/Left$/, 'Right') : code,
    keyCode: vkCode,
    isExtended: (flags & EXTENDED_KEY_MASK) !== 0,
    isInjected: (flags & 0x10) !== 0,
    isUp: (flags & 0x80) !== 0
  }
}
